//go:build ignore

// mksysnum writes zsysnum_linux_<goarch>.go for every GOARCH this repository ships: the name of
// every system call golang.org/x/sys/unix knows for that GOARCH, with its number as a literal, so
// nothing here depends on x/sys. The name is the constant's, lower-cased and without SYS_, which
// is the kernel's __NR_ name (SYS__LLSEEK is _llseek).
//
//	cd internal/sandbox && go run mksysnum.go <directory of golang.org/x/sys/unix> <x/sys version>
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// arches maps each GOARCH to the value of AUDIT_ARCH_* (linux/audit.h) in seccomp_data.arch.
var arches = map[string]string{
	"amd64":  "0xc000003e",
	"arm64":  "0xc00000b7",
	"arm":    "0x40000028",
	"mipsle": "0x40000008",
}

var sysConst = regexp.MustCompile(`(?m)^\s*(SYS_[A-Z0-9_]+)\s*=\s*([0-9]+)\s*$`)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: mksysnum.go <directory of golang.org/x/sys/unix> <x/sys version>")
	}
	dir, version := os.Args[1], os.Args[2]
	goarches := make([]string, 0, len(arches))
	for a := range arches {
		goarches = append(goarches, a)
	}
	sort.Strings(goarches)
	for _, goarch := range goarches {
		src := filepath.Join(dir, "zsysnum_linux_"+goarch+".go")
		data, err := os.ReadFile(src)
		if err != nil {
			log.Fatal(err)
		}
		consts := sysConst.FindAllSubmatch(data, -1)
		if len(consts) == 0 {
			log.Fatalf("%s: no SYS_ constants", src)
		}
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by mksysnum.go from golang.org/x/sys %s unix/zsysnum_linux_%s.go; DO NOT EDIT.\n\n", version, goarch)
		fmt.Fprintf(&b, "//go:build linux && %s\n\npackage sandbox\n\n", goarch)
		fmt.Fprintf(&b, "// auditArch is seccomp_data.arch for a linux/%s process.\nconst auditArch = %s\n\n", goarch, arches[goarch])
		fmt.Fprintf(&b, "// sysnums maps the kernel's name of every linux/%s system call to its number.\nvar sysnums = map[string]uint32{\n", goarch)
		seen := map[string]bool{}
		for _, m := range consts {
			name := strings.ToLower(strings.TrimPrefix(string(m[1]), "SYS_"))
			if seen[name] {
				continue
			}
			seen[name] = true
			fmt.Fprintf(&b, "\t%q: %s,\n", name, m[2])
		}
		b.WriteString("}\n")
		formatted, err := format.Source(b.Bytes())
		if err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile("zsysnum_linux_"+goarch+".go", formatted, 0o644); err != nil {
			log.Fatal(err)
		}
	}
}
